"""Paired validation of deterministic and CVaR outage schedules.

Both final schedules are evaluated on one common bank of operating-state
samples.  Every sample has the same source period, nodal-demand vector,
probability, and contingency catalogue for both schedules.  The default sample
bank is generated by correlated Gaussian perturbations around the three most
critical no-maintenance operating states of the full planning horizon.

The primary loss is aligned with the optimisation engines:

``loss = max_incremental_DNS + w_total * mean_incremental_summed_nodal_DNS``.

The no-maintenance baseline is solved at the same demand and with the same
effective contingency set as the candidate schedule.
"""
